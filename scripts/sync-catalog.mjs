// Vortex catalog sync — single source of truth for cosmetics.
//
// Sources (server truth first):
//   1. VortexBot/data/cosmetics-catalog.json  (ownership, prices, rarity, names, slots)
//   2. vortex-menu-mod .../cosmetics/index.json (type, desc, outfit maps, texture paths)
//
// Outputs (all generated, deterministic, no base64/assets inside JS):
//   data/cosmetics.json
//   data/cosmetics/<cloaks|wings|headwear|pets|auras|bundles>.json
//   cosmetics-store.js            (legacy global shim: var COSMETICS_STORE)
//   ../../MinecraftLauncher/pages/cosmetics/items.js   (launcher Vault data)
//
// Usage: node scripts/sync-catalog.mjs [--bot=...] [--index=...] [--launcher=...] [--no-launcher]
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const args = Object.fromEntries(process.argv.slice(2)
  .filter(a => a.startsWith('--')).map(a => {
    const i = a.indexOf('=');
    return i < 0 ? [a.slice(2), ''] : [a.slice(2, i), a.slice(i + 1)];
  }));

const BOT = resolve(ROOT, args.bot || '../VortexBot/data/cosmetics-catalog.json');
const INDEX = resolve(ROOT, args.index || '../MinecraftLauncher/vortex-menu-mod/src/main/resources/assets/vortex_menu/cosmetics/index.json');
const LAUNCHER = resolve(ROOT, args.launcher || '../MinecraftLauncher/pages/cosmetics/items.js');

const SLOT_TO_CAT = { CAPE: 'cloaks', HEAD: 'headwear', BACK: 'wings', PET: 'pets', AURA: 'auras', SUIT: 'bundles' };
const GEN = '// GENERATED by scripts/sync-catalog.mjs — do not edit by hand. Edit the bot catalog / game index instead.\n';

// Search tags derived from the item's own name tokens (honest descriptors,
// never invented): e.g. "Galaxy Wings" -> [galaxy, wings].
const STOP = new Set(['the', 'of', 'a', 'pet']);
function tagsFor(name, type) {
  const tags = [];
  for (const t of String(name || '').toLowerCase().split(/[^a-z]+/)) {
    if (t.length > 1 && !STOP.has(t) && !tags.includes(t)) tags.push(t);
  }
  const tt = String(type || '').toLowerCase();
  if (tt && !tags.includes(tt)) tags.push(tt);
  return tags;
}

// Render paths (produced by scripts/render-cosmetics.py from the real game
// models). Missing files only warn — cards fall back to letter tiles.
function renderPaths(cat, id) {
  const base = `assets/cosmetics/${cat}/${id}`;
  return {
    preview: base + '/preview.webp',
    thumb: base + '/thumb.webp',
  };
}

function fail(msg) { console.error('sync-catalog: ERROR: ' + msg); process.exit(1); }
function warn(msg) { console.error('sync-catalog: WARN: ' + msg); }

const bot = JSON.parse(readFileSync(BOT, 'utf8'));
const game = JSON.parse(readFileSync(INDEX, 'utf8'));
const byId = new Map((game.cosmetics || []).map(c => [c.id, c]));

const botIds = new Set(bot.all || []);
const gameIds = new Set(byId.keys());
const onlyBot = [...botIds].filter(id => !gameIds.has(id));
const onlyGame = [...gameIds].filter(id => !botIds.has(id));
if (onlyBot.length || onlyGame.length) {
  fail('id parity broken. only-bot=' + JSON.stringify(onlyBot) + ' only-game=' + JSON.stringify(onlyGame));
}

const items = [];
for (const id of bot.all) {
  const g = byId.get(id) || {};
  const slot = bot.slots[id] || g.slot;
  const cat = SLOT_TO_CAT[slot];
  if (!cat) fail('unknown slot for ' + id + ': ' + slot);
  const price = Number(bot.prices[id]);
  if (!Number.isFinite(price) || price <= 0) fail('bad price for ' + id);
  const item = {
    id: String(id).toLowerCase(),
    name: bot.names[id] || g.name || id,
    cat,
    type: g.type || slot,
    slot,
    rarity: bot.rarity[id] || g.rarity || 'Common',
    price,
    desc: g.description || g.desc || '',
    tags: tagsFor(bot.names[id] || g.name || id, g.type || slot),
    ...renderPaths(cat, String(id).toLowerCase()),
  };
  if (g.outfit) item.outfit = g.outfit;
  items.push(item);
  // NOTE: site thumbs deleted by owner request — store cards render letter
  // tiles now. Launcher keeps its own thumbs (separate folder, untouched).
}

const counts = {};
for (const it of items) counts[it.cat] = (counts[it.cat] || 0) + 1;
const updatedAt = new Date().toISOString();

// Site payloads carry no img/thumb paths (no thumbnails in the repo).
const siteItems = items.map(it => {
  const { img, ...rest } = it;
  return rest;
});
mkdirSync(join(ROOT, 'data', 'cosmetics'), { recursive: true });
for (const [cat] of Object.entries(counts)) {
  writeFileSync(join(ROOT, 'data', 'cosmetics', cat + '.json'),
    JSON.stringify({ category: cat, count: counts[cat], updatedAt, items: siteItems.filter(i => i.cat === cat) }, null, 2) + '\n');
}
writeFileSync(join(ROOT, 'data', 'cosmetics.json'),
  JSON.stringify({ updatedAt, total: items.length, counts, starter: bot.starter || [], categories: Object.keys(counts).sort() }, null, 2) + '\n');

// shim for file:// fallback (same shape, no thumbs — letter tiles instead)
const shimItems = siteItems.map(it => ({
  id: it.id, name: it.name, cat: it.cat, type: it.type,
  rarity: it.rarity, price: it.price, desc: it.desc,
  outfit: it.outfit || null,
}));
writeFileSync(join(ROOT, 'cosmetics-store.js'),
  GEN + 'var COSMETICS_STORE = ' + JSON.stringify({ items: shimItems }) + ';\n');

// launcher Vault data (correct slots: CAPE not BACK; suit thumbs from outfit)
if (!('no-launcher' in args)) {
  if (!existsSync(LAUNCHER)) {
    warn('launcher items.js not found, skipped: ' + LAUNCHER);
  } else {
    const launcherItems = items.map(it => {
      const o = { id: it.id, name: it.name, slot: it.slot, type: it.type, rarity: it.rarity, desc: it.desc, thumb: 'cosmetics/' + it.id + '.png' };
      if (it.outfit) {
        o.thumb = 'cosmetics/' + (it.outfit.BACK || it.outfit.PET || Object.values(it.outfit)[0]) + '.png';
        o.outfit = it.outfit;
      }
      return o;
    });
    writeFileSync(LAUNCHER, GEN + 'var COSMETICS = ' + JSON.stringify(launcherItems) + ';\n');
  }
}

console.log(`sync-catalog: ok — ${items.length} items, cats=${JSON.stringify(counts)}`);
