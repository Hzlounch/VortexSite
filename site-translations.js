window.VortexI18n = {
  currentLang: localStorage.getItem('vortex_lang') || 'en',

  init() {
    this.setLanguage(this.currentLang);
  },

  setLanguage(lang) {
    if (!VORTEX_TRANSLATIONS[lang]) lang = 'en';
    this.currentLang = lang;
    localStorage.setItem('vortex_lang', lang);
    document.documentElement.lang = lang;

    const dict = VORTEX_TRANSLATIONS[lang];
    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      if (dict[key]) {
        if (el.tagName === 'INPUT' && el.type === 'placeholder') {
          el.placeholder = dict[key];
        } else {
          el.textContent = dict[key];
        }
      }
    });

    document.querySelectorAll('.lang-btn').forEach(btn => {
      btn.classList.toggle('active', btn.getAttribute('data-lang') === lang);
    });

    window.dispatchEvent(new CustomEvent('vortex-lang-change', { detail: { lang } }));
  }
};

document.addEventListener('DOMContentLoaded', () => {
  window.VortexI18n.init();
});
